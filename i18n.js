/* ------------------------------ 言語の決定 ------------------------------ */

function pickLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q && T[q]) return q;

  let saved = null;
  try { saved = localStorage.getItem('lang'); } catch {}
  if (saved && T[saved]) return saved;

  for (const pref of navigator.languages || [navigator.language || 'en']) {
    if (T[pref]) return pref;                                  // zh-TW, pt-BR
    const base = pref.split('-')[0];
    if (T[base]) return base;                                  // en-US → en
    if (base === 'zh') return 'zh-TW';
    if (base === 'pt') return 'pt-BR';
  }
  return 'en';
}

function applyLang(lang) {
  const dict = T[lang] || T.en;
  const get = (key) => dict[key] ?? T.en[key] ?? '';

  for (const el of document.querySelectorAll('[data-i18n]')) {
    const v = get(el.dataset.i18n);
    if (v) el.textContent = v;
  }
  if (!document.documentElement.hasAttribute('data-no-auto-title')) {
    const titleText = get('title');
    if (titleText) document.title = titleText;
  }
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = get('metaDesc');

  document.documentElement.lang = lang;
  try { localStorage.setItem('lang', lang); } catch {}

  const url = new URL(location.href);
  url.searchParams.set('lang', lang);
  history.replaceState(null, '', url);

  const sel = document.getElementById('lang');
  if (sel) sel.value = lang;
}

